const DICT: Record<Lang, Record<Key, string>> = { de, en };

export type TFn = (k: Key, p?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  const d = DICT[lang];
  return (k, p) => {
    let s: string = d[k] ?? de[k] ?? k;
    if (p) for (const [a, b] of Object.entries(p)) s = s.split(`{${a}}`).join(String(b));
    return s;
  };
}

export const I18nCtx = createContext<{ lang: Lang; t: TFn }>({ lang: 'de', t: makeT('de') });
export const useT = () => useContext(I18nCtx);
